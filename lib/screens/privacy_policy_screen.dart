import 'package:flutter/material.dart';

import '../theme/app_theme.dart';
import '../widgets/pennypal_logo.dart';
import '../widgets/ui_kit.dart';

/// The app's privacy policy.
///
/// Written to be read rather than skimmed past, so it is grouped by what a
/// student actually does in the app, and every claim matches what the code
/// does. The two things people usually look for, "what do you collect" and
/// "who can see my data", are answered in the first two sections.
class PrivacyPolicyScreen extends StatelessWidget {
  const PrivacyPolicyScreen({super.key});

  static const String _updated = 'Last updated: 27 September 2026';

  /// Every section, kept as data so the screen body stays a plain loop and a
  /// wording change does not mean touching the layout.
  static const List<_Section> _sections = [
    _Section(
      icon: Icons.person_outline_rounded,
      title: 'What we collect',
      points: [
        'The account details you type when you register: your name, email '
            'address and phone number.',
        'The transactions, savings goals and budgets you create, along with '
            'the date, amount and category of each one.',
        'A receipt photo, only if you choose to attach one, and only for the '
            'transaction you attach it to.',
        'Messages you send to the admin team through Feedback and Contact '
            'Support.',
        'Questions you ask the AI advisor, so your conversation can be shown '
            'back to you the next time you open it.',
      ],
    ),
    _Section(
      icon: Icons.visibility_outlined,
      title: 'What we do not collect',
      points: [
        'We do not ask for a bank account, card number, or any payment login.',
        'We do not track your location.',
        'We do not run adverts, and we do not sell or share your data with '
            'advertisers.',
        'We do not use your data to build a profile for marketing.',
      ],
    ),
    _Section(
      icon: Icons.admin_panel_settings_outlined,
      title: 'Who can see your data',
      points: [
        'Only you, for your transactions, goals, budgets and chats.',
        'An administrator can see the platform-wide totals on the admin '
            'dashboard, and can open an individual account to review it, '
            'suspend it, or delete it.',
        'An administrator can read the support and feedback messages you send, '
            'because that is how they answer you.',
        'Nobody else. Your data is not shared with any third party.',
      ],
    ),
    _Section(
      icon: Icons.savings_outlined,
      title: 'Where your data is stored',
      points: [
        'Everything is stored in the project\'s own Firebase project.',
        'Your account and its data are filed under a private link that only '
            'your account and the administrators can open.',
        'Receipt photos are stored inside the transaction they belong to, not '
            'in a separate public place.',
      ],
    ),
    _Section(
      icon: Icons.smart_toy_outlined,
      title: 'The AI advisor',
      points: [
        'When you send a question, the text of your question and a short '
            'summary of your own numbers, such as this month\'s spending, are '
            'sent to the Groq API to generate a reply.',
        'Your conversation is saved to your account so the advisor can '
            'remember previous questions.',
        'Do not type anything into the chat that you would be uncomfortable '
            'with leaving on your account.',
        'The AI can be wrong. Check anything important against your own '
            'numbers before acting on it.',
      ],
    ),
    _Section(
      icon: Icons.notifications_none_rounded,
      title: 'Notifications on your phone',
      points: [
        'Budget, spending limit and savings goal alerts can appear as '
            'notifications on your phone.',
        'These are generated by the app itself. We do not use a remote push '
            'service, so your alerts are not relayed through anyone else.',
        'You can turn them off in your phone\'s settings, and switch off the '
            'in-app ones from your profile.',
      ],
    ),
    _Section(
      icon: Icons.delete_outline_rounded,
      title: 'Deleting your account',
      points: [
        'You can ask an administrator to delete your account at any time.',
        'Deleting removes your account, transactions, savings goals, profile '
            'and any messages you sent, permanently.',
        'It cannot be undone, so an administrator will confirm with you '
            'first.',
      ],
    ),
    _Section(
      icon: Icons.shield_outlined,
      title: 'Your choices',
      points: [
        'You can edit your name, phone number, theme and currency whenever you '
            'like.',
        'You can delete individual transactions, goals and milestones yourself.',
        'You can ask an administrator to remove your whole account.',
      ],
    ),
    _Section(
      icon: Icons.mail_outline_rounded,
      title: 'Questions',
      points: [
        'If anything here is unclear, send a query through Contact Support and '
            'an administrator will get back to you.',
      ],
    ),
  ];

  @override
  Widget build(BuildContext context) {
    final isDark = Theme.of(context).brightness == Brightness.dark;
    final muted = isDark ? Colors.white60 : AppColors.textMuted;

    return Scaffold(
      appBar: AppBar(title: const Text('Privacy Policy')),
      body: ListView(
        padding: const EdgeInsets.fromLTRB(
          AppSpace.gutter,
          AppSpace.gutter,
          AppSpace.gutter,
          32,
        ),
        children: [
          Center(
            child: Column(
              children: [
                const PennyPalLogo(size: 68),
                const SizedBox(height: 12),
                const Text(
                  'PennyPal Privacy Policy',
                  style: TextStyle(
                    fontSize: 20,
                    fontWeight: FontWeight.w800,
                    letterSpacing: -0.3,
                  ),
                ),
                const SizedBox(height: 4),
                Text(_updated, style: TextStyle(fontSize: 12, color: muted)),
              ],
            ),
          ),
          const SizedBox(height: 18),
          SurfaceCard(
            color: isDark ? Colors.white10 : AppColors.brandTint,
            child: Text(
              'PennyPal is a budgeting app for students. We collect the '
              'minimum we need to let you track your money, and we keep it to '
              'yourself. This page explains exactly what that means.',
              style: TextStyle(
                fontSize: 13.5,
                height: 1.55,
                color: isDark ? Colors.white : AppColors.brandDark,
              ),
            ),
          ),
          const SizedBox(height: AppSpace.section),
          for (final s in _sections) ...[
            _PolicySection(section: s, muted: muted),
            const SizedBox(height: AppSpace.gap),
          ],
          const SizedBox(height: 8),
          Text(
            'This policy is part of the PennyPal student project. It describes '
            'how the app actually behaves, not an aspirational version of it.',
            textAlign: TextAlign.center,
            style: TextStyle(
              fontSize: 11.5,
              height: 1.45,
              color: isDark ? Colors.white38 : AppColors.textMuted,
            ),
          ),
        ],
      ),
    );
  }
}

class _PolicySection extends StatelessWidget {
  final _Section section;
  final Color muted;

  const _PolicySection({required this.section, required this.muted});

  @override
  Widget build(BuildContext context) {
    final isDark = Theme.of(context).brightness == Brightness.dark;
    return SurfaceCard(
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              Container(
                width: 34,
                height: 34,
                decoration: BoxDecoration(
                  color: isDark ? Colors.white10 : AppColors.brandTint,
                  borderRadius: BorderRadius.circular(10),
                ),
                child: Icon(section.icon, size: 18, color: AppColors.brand),
              ),
              const SizedBox(width: 11),
              Expanded(
                child: Text(
                  section.title,
                  style: const TextStyle(
                    fontSize: 15,
                    fontWeight: FontWeight.w800,
                  ),
                ),
              ),
            ],
          ),
          const SizedBox(height: 12),
          for (final point in section.points)
            Padding(
              padding: const EdgeInsets.only(bottom: 8),
              child: Row(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Padding(
                    padding: const EdgeInsets.only(top: 7, right: 9),
                    child: Container(
                      width: 5,
                      height: 5,
                      decoration: BoxDecoration(
                        color: AppColors.brand.withValues(alpha: 0.7),
                        shape: BoxShape.circle,
                      ),
                    ),
                  ),
                  Expanded(
                    child: Text(
                      point,
                      style: const TextStyle(fontSize: 13.5, height: 1.5),
                    ),
                  ),
                ],
              ),
            ),
        ],
      ),
    );
  }
}

class _Section {
  final IconData icon;
  final String title;
  final List<String> points;

  const _Section({
    required this.icon,
    required this.title,
    required this.points,
  });
}
